#!/usr/bin/env python3
"""Build the SQL files and deploy the console to dash-server (http://127.0.0.1:<HC_DASH_PORT>/apps/<HC_APP>).

    .venv/bin/python dash/deploy.py

Idempotent: creates the app on the first run, replaces its files after that, deploys live (rolling back on a failed
health check) and prints the probes. The SQL comes from console.QUERIES, so the files can never drift from the code.
"""
import json
import sys
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import console  # noqa: E402
import hcconfig as C  # noqa: E402  (dash/site_config.py put the repository root on sys.path)

APP, TITLE, PROFILE = C.APP, "Hospital group · one patient, every branch", C.DASH_PROFILE
MCP = f"http://127.0.0.1:{C.DASH_PORT}/mcp"
MODULES = ["app.py", "console.py", "story.py", "scans.py", "embed.py", "agent_tab.py", "flow.py", "how.py", "theme.py", "page_css.py"]
REQUIREMENTS = "# for the PACS tab: sign S3 links, and render a DICOM file live\nboto3>=1.34\npydicom>=2.4\nnumpy>=1.26\npillow>=10\n"


def call(name, args):
    body = json.dumps({"jsonrpc": "2.0", "id": 1, "method": "tools/call", "params": {"name": name, "arguments": args}}).encode()
    req = urllib.request.Request(MCP, data=body, headers={"Content-Type": "application/json", "Accept": "application/json, text/event-stream"})
    raw = urllib.request.urlopen(req, timeout=900).read().decode()
    for line in raw.splitlines():
        if line.startswith("data: "):
            raw = line[6:]
    payload = json.loads(raw)
    if "error" in payload:
        raise SystemExit(f"{name} failed: {payload['error']}")
    res = payload["result"]
    text = "\n".join(c.get("text", "") for c in res.get("content", []))
    data = res.get("structuredContent") or {}
    if not data and "Result:" in text:
        data = json.loads(text[text.find("Result:") + 7:])
    if res.get("isError"):
        raise SystemExit(f"{name} failed:\n{text[:3000]}")
    return text.split("\n", 1)[0], data


def site_config():
    """dash-server runs its own copy of the app, outside this repository: freeze the paths and the bucket into it."""
    vals = {"ROOT": str(C.ROOT), "BUCKET": C.S3_BUCKET, "REGION": C.S3_REGION, "KEYFILE": str(C.S3_KEY_FILE), "PY": str(C.PY)}
    return ('"""Generated by dash/deploy.py from config.env: where the console finds the repository, the bucket and the key."""\n'
            + "".join(f"{k} = {v!r}\n" for k, v in vals.items()))


def files():
    out = [{"path": m, "content": (HERE / m).read_text()} for m in MODULES]
    out.append({"path": "site_config.py", "content": site_config()})
    out.append({"path": "assets/exasol_logo_dark.svg", "content": (HERE / "assets" / "exasol_logo_dark.svg").read_text()})
    out += [{"path": f"queries/business/{k}.sql", "content": v.strip() + "\n"} for k, v in console.QUERIES.items()]
    out += [{"path": f"explain/{k}.sql", "content": "EXPLAIN VIRTUAL " + v.strip() + "\n"} for k, v in console.EXPLAIN.items()]
    out.append({"path": "queries/sql_smoke.json", "content": json.dumps(console.SMOKE, indent=2) + "\n"})
    out.append({"path": "requirements.txt", "content": REQUIREMENTS})
    manifest = {"name": APP, "title": TITLE, "route": f"/apps/{APP}",
                "description": "Healthcare federation demo: legacy HIS (Postgres), modern EHR (MongoDB) and PACS (S3) through one Exasol endpoint.",
                "template": "exasol-analytics",
                "data_sources": {"primary": {"kind": "exasol", "profile": PROFILE, "auth_mode": "local_direct"}}}
    out.append({"path": "dash-app.json", "content": json.dumps(manifest, ensure_ascii=False, indent=2) + "\n"})
    return out


def main():
    fs = files()
    _, inv = call("apps_list", {})
    if APP not in {a.get("name") for a in inv.get("apps", [])}:
        head, _ = call("app_create_from_files", {"name": APP, "title": TITLE, "template": "exasol-analytics", "files": fs,
                                                 "start_immediately": False})
        print(f"create   : {head}")
    else:
        head, _ = call("app_put_files", {"name": APP, "files": fs})
        print(f"files    : {head} ({len(fs)} files)")
    head, v = call("app_validate", {"name": APP})
    print(f"validate : {head}")
    head, _ = call("app_deploy_draft", {"name": APP, "deployment_target": "live", "auto_rollback_on_health_failure": True})
    print(f"deploy   : {head}")
    _, h = call("app_run_healthcheck", {"name": APP, "target": "live"})
    for p in h.get("health", {}).get("probes", []):
        print(f"  {p.get('status'):10} {p.get('name')}")
    print(f"\nhttp://127.0.0.1:{C.DASH_PORT}/apps/{APP}")


if __name__ == "__main__":
    main()
