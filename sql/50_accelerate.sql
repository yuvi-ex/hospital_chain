-- HOSP_ACCEL: federate first, then copy only what people ask about every day. One statement builds it from the live
-- sources (Postgres + MongoDB through the master patient index); the readmission definition is the same SQL as HOSP_CORE.
CREATE SCHEMA IF NOT EXISTS HOSP_ACCEL;

CREATE OR REPLACE TABLE HOSP_ACCEL.ENCOUNTERS AS
SELECT UNIFIED_ID, ENCOUNTER_ID, RECORD_ID, SOURCE_SYSTEM, BRANCH, ENCOUNTER_CLASS, DEPARTMENT, ADMIT_DATE, DISCHARGE_DATE,
       STATUS, DX_CODE, DIAGNOSIS, LENGTH_OF_STAY, CURRENT_TIMESTAMP AS COPIED_AT
FROM HOSP_CORE.ENCOUNTERS;

CREATE OR REPLACE VIEW HOSP_ACCEL.READMISSIONS_30D AS
WITH ip AS (
  SELECT UNIFIED_ID, RECORD_ID, ENCOUNTER_ID, SOURCE_SYSTEM, BRANCH, ADMIT_DATE, DISCHARGE_DATE, DIAGNOSIS,
         LAG(DISCHARGE_DATE) OVER (PARTITION BY UNIFIED_ID ORDER BY ADMIT_DATE, ENCOUNTER_ID) AS PREV_DISCHARGE,
         LAG(RECORD_ID) OVER (PARTITION BY UNIFIED_ID ORDER BY ADMIT_DATE, ENCOUNTER_ID) AS PREV_RECORD_ID,
         LAG(BRANCH) OVER (PARTITION BY UNIFIED_ID ORDER BY ADMIT_DATE, ENCOUNTER_ID) AS PREV_BRANCH,
         LAG(ENCOUNTER_ID) OVER (PARTITION BY UNIFIED_ID ORDER BY ADMIT_DATE, ENCOUNTER_ID) AS PREV_ENCOUNTER_ID
  FROM HOSP_ACCEL.ENCOUNTERS WHERE ENCOUNTER_CLASS = 'inpatient')
SELECT UNIFIED_ID, ENCOUNTER_ID, BRANCH, SOURCE_SYSTEM, ADMIT_DATE, DIAGNOSIS, PREV_ENCOUNTER_ID, PREV_BRANCH, PREV_DISCHARGE,
       DAYS_BETWEEN(ADMIT_DATE, PREV_DISCHARGE) AS DAYS_SINCE_DISCHARGE,
       CASE WHEN PREV_RECORD_ID = RECORD_ID THEN TRUE ELSE FALSE END AS VISIBLE_TO_ONE_SYSTEM
FROM ip
WHERE PREV_DISCHARGE IS NOT NULL AND DAYS_BETWEEN(ADMIT_DATE, PREV_DISCHARGE) BETWEEN 0 AND 30;
