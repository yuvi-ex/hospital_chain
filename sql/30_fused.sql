-- HOSP_CORE: the fused, live picture. Every view joins live source data to the master patient index (UNIFIED_ID).
-- Rule learned the hard way on 2026.2.0-nano.3: an aggregate with NO group key (or a GROUP BY expression) over a
-- UNION ALL of virtual-schema views aborts the session (assert in querycreationvisitor.cpp). Always GROUP BY a column.

CREATE OR REPLACE VIEW HOSP_CORE.ENCOUNTERS AS
SELECT m.UNIFIED_ID, e.*, DAYS_BETWEEN(e.DISCHARGE_DATE, e.ADMIT_DATE) AS LENGTH_OF_STAY
FROM HOSP_SRC.ALL_ENCOUNTERS e JOIN HOSP_CORE.MPI m ON m.RECORD_ID = e.RECORD_ID;

CREATE OR REPLACE VIEW HOSP_CORE.ALLERGIES AS
SELECT m.UNIFIED_ID, a.* FROM HOSP_SRC.ALL_ALLERGIES a JOIN HOSP_CORE.MPI m ON m.RECORD_ID = a.RECORD_ID;

CREATE OR REPLACE VIEW HOSP_CORE.MEDICATIONS AS
SELECT m.UNIFIED_ID, x.*, c.DRUG_CLASS
FROM HOSP_SRC.ALL_MEDICATIONS x JOIN HOSP_CORE.MPI m ON m.RECORD_ID = x.RECORD_ID
LEFT JOIN HOSP_CORE.DRUG_CLASS c ON c.DRUG = UPPER(x.DRUG);

-- Diabetes, as either system knows it: a coded condition (EHR), a diabetes diagnosis or an HbA1c test (legacy).
CREATE OR REPLACE VIEW HOSP_CORE.DIABETIC_PATIENTS AS
SELECT DISTINCT m.UNIFIED_ID FROM HOSP_SRC.MODERN_CONDITIONS c JOIN HOSP_CORE.MPI m ON m.RECORD_ID = c.RECORD_ID WHERE c.CONDITION_CODE LIKE 'E11%'
UNION
SELECT DISTINCT m.UNIFIED_ID FROM HOSP_LEGACY.LAB_RSLT l JOIN HOSP_LEGACY.VISIT_HDR v ON v.VISIT_NO = l.VISIT_NO
  JOIN HOSP_CORE.MPI m ON m.RECORD_ID = v.PAT_NO WHERE l.TEST_CD = 'HBA1C';

-- The safety check: a CURRENT order (draft or active, any system) for a drug in a class the patient is allergic to,
-- with the allergy recorded in ANY system. KNOWN_WHERE_PRESCRIBED says whether the prescribing system could have seen it.
CREATE OR REPLACE VIEW HOSP_CORE.ALLERGY_CONFLICTS AS
SELECT o.UNIFIED_ID, o.ENCOUNTER_ID, o.SOURCE_SYSTEM AS PRESCRIBED_IN, o.RECORD_ID AS PRESCRIBED_UNDER, o.DRUG, o.DOSE, o.ORDER_STATUS,
       o.DRUG_CLASS, a.ALLERGY_AS_RECORDED, a.SEVERITY, a.SOURCE_SYSTEM AS ALLERGY_RECORDED_IN, a.RECORD_ID AS ALLERGY_RECORD_ID,
       CASE WHEN a.RECORD_ID = o.RECORD_ID THEN TRUE ELSE FALSE END AS KNOWN_WHERE_PRESCRIBED
FROM HOSP_CORE.MEDICATIONS o
JOIN HOSP_CORE.ALLERGIES a ON a.UNIFIED_ID = o.UNIFIED_ID AND a.DRUG_CLASS = o.DRUG_CLASS
WHERE o.ORDER_STATUS IN ('draft', 'active');

-- 30-day readmission, the certified definition: an inpatient admission within 30 days of the same PERSON's previous
-- inpatient discharge, at any branch, in any system. VISIBLE_TO_ONE_SYSTEM: the previous stay is under the same record id,
-- i.e. the branch system on its own would have counted it.
CREATE OR REPLACE VIEW HOSP_CORE.READMISSIONS_30D AS
WITH ip AS (
  SELECT UNIFIED_ID, RECORD_ID, ENCOUNTER_ID, SOURCE_SYSTEM, BRANCH, ADMIT_DATE, DISCHARGE_DATE, DIAGNOSIS,
         LAG(DISCHARGE_DATE) OVER (PARTITION BY UNIFIED_ID ORDER BY ADMIT_DATE, ENCOUNTER_ID) AS PREV_DISCHARGE,
         LAG(RECORD_ID) OVER (PARTITION BY UNIFIED_ID ORDER BY ADMIT_DATE, ENCOUNTER_ID) AS PREV_RECORD_ID,
         LAG(BRANCH) OVER (PARTITION BY UNIFIED_ID ORDER BY ADMIT_DATE, ENCOUNTER_ID) AS PREV_BRANCH,
         LAG(ENCOUNTER_ID) OVER (PARTITION BY UNIFIED_ID ORDER BY ADMIT_DATE, ENCOUNTER_ID) AS PREV_ENCOUNTER_ID
  FROM HOSP_CORE.ENCOUNTERS WHERE ENCOUNTER_CLASS = 'inpatient')
SELECT UNIFIED_ID, ENCOUNTER_ID, BRANCH, SOURCE_SYSTEM, ADMIT_DATE, DIAGNOSIS, PREV_ENCOUNTER_ID, PREV_BRANCH, PREV_DISCHARGE,
       DAYS_BETWEEN(ADMIT_DATE, PREV_DISCHARGE) AS DAYS_SINCE_DISCHARGE,
       CASE WHEN PREV_RECORD_ID = RECORD_ID THEN TRUE ELSE FALSE END AS VISIBLE_TO_ONE_SYSTEM
FROM ip
WHERE PREV_DISCHARGE IS NOT NULL AND DAYS_BETWEEN(ADMIT_DATE, PREV_DISCHARGE) BETWEEN 0 AND 30;

-- Similar cases: cosine similarity between notes is a join + GROUP BY over the long, narrow vector table.
-- Usage: WHERE q.NOTE_ID = '<note>' ; the text of each note stays in its source system.
CREATE OR REPLACE VIEW HOSP_CORE.NOTES AS
SELECT n.NOTE_ID, n.SOURCE_SYSTEM, n.RECORD_ID, n.ENCOUNTER_ID, m.UNIFIED_ID
FROM HOSP_CORE.NOTE_INDEX n JOIN HOSP_CORE.MPI m ON m.RECORD_ID = n.RECORD_ID;
