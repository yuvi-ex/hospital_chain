-- LIKE, not REGEXP_LIKE: the Postgres dialect pushes these expressions down and Postgres has no REGEXP_LIKE.
-- HOSP_SRC: the sources, read live, translated into one vocabulary. Views only: nothing is stored.
-- Every view reads a virtual schema (Postgres legacy HIS, MongoDB modern EHR) on each query.
CREATE SCHEMA IF NOT EXISTS HOSP_SRC;

-- ---------------------------------------------------------------- legacy HIS (Postgres): text dates, initials, free text
CREATE OR REPLACE VIEW HOSP_SRC.LEGACY_PATIENTS AS
WITH raw AS (
  SELECT p.PAT_NO, p.BRANCH_CD, p.PAT_NM, p.SEX, p.DOB_TXT, p.AGE_YRS, p.PH_NO, p.CITY,
         REGEXP_SUBSTR(p.PAT_NM, '[^ ]+', 1, 1) AS T1, REGEXP_SUBSTR(p.PAT_NM, '[^ ]+', 1, 2) AS T2
  FROM HOSP_LEGACY.PAT_MSTR p)
SELECT PAT_NO AS RECORD_ID, 'LEGACY_HIS' AS SOURCE_SYSTEM, BRANCH_CD AS BRANCH, PAT_NM AS NAME_AS_RECORDED,
       CASE WHEN LENGTH(REPLACE(T1, '.', '')) <= 1 THEN T2 ELSE T1 END AS GIVEN_NAME,
       CASE WHEN LENGTH(REPLACE(T1, '.', '')) <= 1 THEN REPLACE(T1, '.', '') ELSE T2 END AS FAMILY_NAME,   -- often only an initial
       SEX,
       CASE WHEN DOB_TXT LIKE '__/__/____' THEN TO_DATE(DOB_TXT, 'DD/MM/YYYY')
            WHEN DOB_TXT LIKE '__-__-__' THEN TO_DATE(SUBSTR(DOB_TXT, 1, 6)
                 || CASE WHEN CAST(SUBSTR(DOB_TXT, 7, 2) AS DECIMAL(2,0)) >= 27 THEN '19' ELSE '20' END || SUBSTR(DOB_TXT, 7, 2), 'DD-MM-YYYY')
       END AS BIRTH_DATE,
       -- the same text read the other way round: front desks swap day and month when both are <= 12
       CASE WHEN DOB_TXT LIKE '__/__/____' AND CAST(SUBSTR(DOB_TXT, 1, 2) AS DECIMAL(2,0)) <= 12
             AND CAST(SUBSTR(DOB_TXT, 4, 2) AS DECIMAL(2,0)) <> CAST(SUBSTR(DOB_TXT, 1, 2) AS DECIMAL(2,0))
            THEN TO_DATE(DOB_TXT, 'MM/DD/YYYY') END AS BIRTH_DATE_SWAPPED,
       DOB_TXT AS BIRTH_DATE_AS_RECORDED, AGE_YRS AS AGE_ONLY,
       -- a 10-digit Indian mobile starts with 6-9; 0000xxxxxx is this demo's synthetic, undiallable range
       CASE WHEN LENGTH(PH_NO) = 10 AND (SUBSTR(PH_NO, 1, 1) IN ('6', '7', '8', '9') OR PH_NO LIKE '0000%') THEN PH_NO END AS MOBILE,
       INITCAP(CITY) AS CITY
FROM raw;

CREATE OR REPLACE VIEW HOSP_SRC.LEGACY_ENCOUNTERS AS
SELECT v.VISIT_NO AS ENCOUNTER_ID, v.PAT_NO AS RECORD_ID, 'LEGACY_HIS' AS SOURCE_SYSTEM, v.BRANCH_CD AS BRANCH,
       CASE v.VISIT_TYP WHEN 'IP' THEN 'inpatient' WHEN 'ER' THEN 'emergency' ELSE 'outpatient' END AS ENCOUNTER_CLASS,
       CASE v.DEPT_CD WHEN 'PULM' THEN 'Pulmonology' WHEN 'CARD' THEN 'Cardiology' WHEN 'NEURO' THEN 'Neurology'
            WHEN 'MED' THEN 'General Medicine' WHEN 'ENDO' THEN 'Endocrinology' WHEN 'ONCO' THEN 'Oncology'
            WHEN 'ORTHO' THEN 'Orthopaedics' ELSE 'Emergency' END AS DEPARTMENT,
       TO_DATE(v.ADM_DT, 'DD/MM/YYYY') AS ADMIT_DATE, TO_DATE(v.DIS_DT, 'DD/MM/YYYY') AS DISCHARGE_DATE,
       'finished' AS STATUS, v.DX_CD AS DX_CODE, INITCAP(v.DX_DESC) AS DIAGNOSIS
FROM HOSP_LEGACY.VISIT_HDR v;

CREATE OR REPLACE VIEW HOSP_SRC.LEGACY_ALLERGIES AS
SELECT a.PAT_NO AS RECORD_ID, 'LEGACY_HIS' AS SOURCE_SYSTEM, a.ALRGY_NOTE AS ALLERGY_AS_RECORDED,
       CASE WHEN (UPPER(a.ALRGY_NOTE) LIKE '%PENICILLIN%' OR UPPER(a.ALRGY_NOTE) LIKE '%AMOXY%' OR UPPER(a.ALRGY_NOTE) LIKE '%AMPICILLIN%' OR UPPER(a.ALRGY_NOTE) LIKE '%PEN ALLERGY%' OR UPPER(a.ALRGY_NOTE) LIKE '%BETA-LACTAM%') THEN 'PENICILLIN'
            WHEN (UPPER(a.ALRGY_NOTE) LIKE '%SULPHA%' OR UPPER(a.ALRGY_NOTE) LIKE '%SULFA%') THEN 'SULFONAMIDE'
            WHEN (UPPER(a.ALRGY_NOTE) LIKE '%NSAID%' OR UPPER(a.ALRGY_NOTE) LIKE '%IBUPROFEN%' OR UPPER(a.ALRGY_NOTE) LIKE '%DICLOFENAC%') THEN 'NSAID'
            WHEN (UPPER(a.ALRGY_NOTE) LIKE '%CEFTRIAXONE%' OR UPPER(a.ALRGY_NOTE) LIKE '%CEPHALO%') THEN 'CEPHALOSPORIN' END AS DRUG_CLASS,
       CASE WHEN (UPPER(a.ALRGY_NOTE) LIKE '%ANAPHYLAXIS%' OR UPPER(a.ALRGY_NOTE) LIKE '%STEVENS%' OR UPPER(a.ALRGY_NOTE) LIKE '%ANGIOEDEMA%' OR UPPER(a.ALRGY_NOTE) LIKE '%BRONCHOSPASM%') THEN 'severe' ELSE 'moderate' END AS SEVERITY
FROM HOSP_LEGACY.ALRGY_TXT a
WHERE UPPER(a.ALRGY_NOTE) NOT IN ('NKDA', 'NO KNOWN ALLERGY', 'NIL');

CREATE OR REPLACE VIEW HOSP_SRC.LEGACY_MEDICATIONS AS
SELECT r.VISIT_NO AS ENCOUNTER_ID, v.PAT_NO AS RECORD_ID, 'LEGACY_HIS' AS SOURCE_SYSTEM, INITCAP(r.DRUG_NM) AS DRUG,
       r.DOSE_TXT AS DOSE, 'completed' AS ORDER_STATUS
FROM HOSP_LEGACY.RX_LINE r JOIN HOSP_LEGACY.VISIT_HDR v ON v.VISIT_NO = r.VISIT_NO;

-- ---------------------------------------------------------------- modern EHR (MongoDB): nested documents become child tables
CREATE OR REPLACE VIEW HOSP_SRC.MODERN_PATIENTS AS
SELECT p."mongo_id" AS RECORD_ID, 'MODERN_EHR' AS SOURCE_SYSTEM, p."homeBranch" AS BRANCH, n."text" AS NAME_AS_RECORDED,
       UPPER(n."given") AS GIVEN_NAME, UPPER(n."family") AS FAMILY_NAME,
       CASE p."gender" WHEN 'female' THEN 'F' WHEN 'male' THEN 'M' END AS SEX,
       TO_DATE(p."birthDate", 'YYYY-MM-DD') AS BIRTH_DATE, p."birthDate" AS BIRTH_DATE_AS_RECORDED,
       RIGHT(t."mobile", 10) AS MOBILE, a."city" AS CITY, p."allergies|array" AS ALLERGIES_RECORDED
FROM HOSP_EHR_PATIENTS.PATIENTS p
LEFT JOIN HOSP_EHR_PATIENTS."PATIENTS_name" n ON n."_id" = p."name|object"
LEFT JOIN HOSP_EHR_PATIENTS."PATIENTS_telecom" t ON t."_id" = p."telecom|object"
LEFT JOIN HOSP_EHR_PATIENTS."PATIENTS_address" a ON a."_id" = p."address|object";

CREATE OR REPLACE VIEW HOSP_SRC.MODERN_CONDITIONS AS
SELECT p."mongo_id" AS RECORD_ID, c."code" AS CONDITION_CODE, c."display" AS CONDITION_NAME
FROM HOSP_EHR_PATIENTS."PATIENTS_conditions_arr" c JOIN HOSP_EHR_PATIENTS.PATIENTS p ON p."_id" = c."_parent";

CREATE OR REPLACE VIEW HOSP_SRC.MODERN_ALLERGIES AS
SELECT p."mongo_id" AS RECORD_ID, 'MODERN_EHR' AS SOURCE_SYSTEM, al."substance" || ' (' || al."reaction" || ')' AS ALLERGY_AS_RECORDED,
       CASE WHEN (UPPER(al."substance") LIKE '%PENICILLIN%' OR UPPER(al."substance") LIKE '%AMOXY%' OR UPPER(al."substance") LIKE '%AMPICILLIN%') THEN 'PENICILLIN'
            WHEN (UPPER(al."substance") LIKE '%SULPHA%' OR UPPER(al."substance") LIKE '%SULFA%' OR UPPER(al."substance") LIKE '%SULFONAMIDE%') THEN 'SULFONAMIDE'
            WHEN (UPPER(al."substance") LIKE '%NSAID%' OR UPPER(al."substance") LIKE '%IBUPROFEN%' OR UPPER(al."substance") LIKE '%DICLOFENAC%') THEN 'NSAID'
            WHEN (UPPER(al."substance") LIKE '%CEFTRIAXONE%' OR UPPER(al."substance") LIKE '%CEPHALO%') THEN 'CEPHALOSPORIN' END AS DRUG_CLASS,
       al."severity" AS SEVERITY
FROM HOSP_EHR_PATIENTS."PATIENTS_allergies_arr" al JOIN HOSP_EHR_PATIENTS.PATIENTS p ON p."_id" = al."_parent";

CREATE OR REPLACE VIEW HOSP_SRC.MODERN_ENCOUNTERS AS
SELECT e."mongo_id" AS ENCOUNTER_ID, e."patientId" AS RECORD_ID, 'MODERN_EHR' AS SOURCE_SYSTEM, e."branch" AS BRANCH,
       e."class" AS ENCOUNTER_CLASS, e."department" AS DEPARTMENT,
       TO_DATE(SUBSTR(e."admitted", 1, 10), 'YYYY-MM-DD') AS ADMIT_DATE, TO_DATE(e."discharged", 'YYYY-MM-DD') AS DISCHARGE_DATE,
       e."status" AS STATUS, d."code" AS DX_CODE, d."display" AS DIAGNOSIS
FROM HOSP_EHR_ENCOUNTERS.ENCOUNTERS e
LEFT JOIN HOSP_EHR_ENCOUNTERS."ENCOUNTERS_diagnosis" d ON d."_id" = e."diagnosis|object";

CREATE OR REPLACE VIEW HOSP_SRC.MODERN_MEDICATIONS AS
SELECT e."mongo_id" AS ENCOUNTER_ID, e."patientId" AS RECORD_ID, 'MODERN_EHR' AS SOURCE_SYSTEM, m."name" AS DRUG, m."dose" AS DOSE,
       m."status" AS ORDER_STATUS
FROM HOSP_EHR_ENCOUNTERS."ENCOUNTERS_medications_arr" m JOIN HOSP_EHR_ENCOUNTERS.ENCOUNTERS e ON e."_id" = m."_parent";

CREATE OR REPLACE VIEW HOSP_SRC.MODERN_OBSERVATIONS AS
SELECT e."mongo_id" AS ENCOUNTER_ID, e."patientId" AS RECORD_ID, o."code" AS OBS_CODE, o."value" AS OBS_VALUE, o."unit" AS UNIT
FROM HOSP_EHR_ENCOUNTERS."ENCOUNTERS_observations_arr" o JOIN HOSP_EHR_ENCOUNTERS.ENCOUNTERS e ON e."_id" = o."_parent";

-- ---------------------------------------------------------------- one vocabulary across both systems
CREATE OR REPLACE VIEW HOSP_SRC.ALL_ENCOUNTERS AS
SELECT * FROM HOSP_SRC.LEGACY_ENCOUNTERS UNION ALL SELECT * FROM HOSP_SRC.MODERN_ENCOUNTERS;
CREATE OR REPLACE VIEW HOSP_SRC.ALL_ALLERGIES AS
SELECT * FROM HOSP_SRC.LEGACY_ALLERGIES UNION ALL SELECT * FROM HOSP_SRC.MODERN_ALLERGIES;
CREATE OR REPLACE VIEW HOSP_SRC.ALL_MEDICATIONS AS
SELECT * FROM HOSP_SRC.LEGACY_MEDICATIONS UNION ALL SELECT * FROM HOSP_SRC.MODERN_MEDICATIONS;

